"""**3. Model 1: GCN Architecture**"""

class GCN(torch.nn.Module):

    def __init__(
        self,
        input_dim,
        hidden_dim,
        output_dim,
        dropout=0.5,
        improved=True
    ):

        super(GCN, self).__init__()

        # cached=True: the graph is fixed across epochs (transductive, full-batch),
        # so the normalized adjacency only needs to be computed once instead of
        # on every forward call. This is a major CPU speedup with no accuracy cost.
        # NOTE: only safe with cached=True as long as you always pass the SAME
        # edge_index — if you ever change the graph between calls, set this False.
        self.conv1 = GCNConv(
            input_dim,
            hidden_dim,
            improved=improved,
            cached=True
        )

        self.conv2 = GCNConv(
            hidden_dim,
            hidden_dim,
            improved=improved,
            cached=True
        )

        self.conv3 = GCNConv(
            hidden_dim,
            output_dim,
            improved=improved,
            cached=True
        )

        self.bn1 = torch.nn.BatchNorm1d(hidden_dim)
        self.bn2 = torch.nn.BatchNorm1d(hidden_dim)

        self.dropout = dropout


    def forward(
        self,
        x,
        edge_index
    ):

        x1 = self.conv1(
            x,
            edge_index
        )
        x1 = self.bn1(x1)
        x1 = F.relu(x1)
        x1 = F.dropout(
            x1,
            p=self.dropout,
            training=self.training
        )

        x2 = self.conv2(
            x1,
            edge_index
        )
        x2 = self.bn2(x2)
        # Residual connection: helps counter over-smoothing across layers
        x2 = F.relu(x2) + x1
        x2 = F.dropout(
            x2,
            p=self.dropout,
            training=self.training
        )

        out = self.conv3(
            x2,
            edge_index
        )

        return out

"""**4. Model 2: GraphSAGE Architecture**

"""

class GraphSAGE(torch.nn.Module):

    def __init__(
        self,
        input_dim,
        hidden_dim,
        output_dim,
        dropout=0.5
    ):
        super(GraphSAGE, self).__init__()
        self.sage1 = SAGEConv(
            input_dim,
            hidden_dim
        )

        self.sage2 = SAGEConv(
            hidden_dim,
            hidden_dim
        )

        self.sage3 = SAGEConv(
            hidden_dim,
            output_dim
        )

        self.bn1 = torch.nn.BatchNorm1d(hidden_dim)
        self.bn2 = torch.nn.BatchNorm1d(hidden_dim)

        self.dropout = dropout

    def forward(
        self,
        x,
        edge_index
    ):

        x1 = self.sage1(
            x,
            edge_index
        )
        x1 = self.bn1(x1)
        x1 = F.relu(x1)
        x1 = F.dropout(
            x1,
            p=self.dropout,
            training=self.training
        )

        x2 = self.sage2(
            x1,
            edge_index
        )
        x2 = self.bn2(x2)
        # Residual connection: helps counter over-smoothing across layers
        x2 = F.relu(x2) + x1
        x2 = F.dropout(
            x2,
            p=self.dropout,
            training=self.training
        )

        out = self.sage3(
            x2,
            edge_index
        )

        return out

